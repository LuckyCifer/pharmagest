class Command(BaseCommand):
    help = 'Insère les médicaments et compléments Neolife de démonstration'

    def handle(self, *args, **options):
        self.stdout.write('Création des catégories...')
        cats = {}
        for nom in CATEGORIES:
            c, _ = Categorie.objects.get_or_create(nom=nom)
            cats[nom] = c

        self.stdout.write('Création des fournisseurs...')
        fours = {}
        for data in FOURNISSEURS:
            f, _ = Fournisseur.objects.get_or_create(
                nom=data['nom'],
                defaults={'contact': data['contact'], 'email': data['email']},
            )
            fours[data['nom']] = f

        self.stdout.write('Insertion des médicaments...')
        created = 0
        skipped = 0
        for m in MEDICAMENTS:
            if Medicament.objects.filter(nom=m['nom']).exists():
                skipped += 1
                continue
            Medicament.objects.create(
                nom=m['nom'],
                denomination_commune=m.get('denomination_commune', ''),
                forme=m['forme'],
                dosage=m.get('dosage', ''),
                categorie=cats[m['categorie']],
                fournisseur=fours[m['fournisseur']],
                numero_lot=m.get('numero_lot', ''),
                date_fabrication=m.get('date_fabrication'),
                date_peremption=m.get('date_peremption'),
                prix_achat=m['prix_achat'],
                prix_vente=m['prix_vente'],
                quantite_stock=m['quantite_stock'],
                seuil_alerte=m['seuil_alerte'],
                description=m.get('description', ''),
            )
            created += 1

        self.stdout.write(self.style.SUCCESS(
            f'\nTermine -- {created} medicament(s) cree(s), {skipped} deja existant(s).'
        ))
